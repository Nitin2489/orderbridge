/**
 * A plain SHA-256 (FIPS 180-4) for tests only.
 *
 * jsdom has no SubtleCrypto, and src/ may not import Node modules (see
 * eslint.config.mjs), so tests install a SubtleCrypto stand-in built on
 * this. It is checked against standard test vectors and against digests
 * computed independently (src/test/sha256.test.ts). Never used by the app,
 * which only calls the browser's crypto.subtle.digest.
 */

